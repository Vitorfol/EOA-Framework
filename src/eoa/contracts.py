"""Data contracts and validation schemas.

These schemas formalize the three levels of explainability defined in the
foundational architecture:
- Level 1: Analytical model predictions (PredictionArtifact)
- Level 2: Raw explainability attributions (XAIArtifact)
- Domain Context: Structured operational metadata and schemas (DomainContext)
- Level 3: Contextualized, validated explanations (ExplanationResponse & AgentStepTrace)

All models are strictly based on Pydantic v2 with native JSON serialization,
strict validation constraints, and flexible ingestion (supporting both typed
objects and plain Python dictionaries).
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator


class PredictionArtifact(BaseModel):
    """Represents the raw analytical prediction output (Level 1).

    Encapsulates what was predicted by the machine learning pipeline,
    its confidence or probability, and relevant model metadata.

    Attributes:
        target_variable: Name or identifier of target variable being predicted.
        predicted_value: The predicted class label, numerical value, or state.
        model_name: Optional name or version identifier of the source model.
        confidence_or_probability: Optional prediction confidence score (0.0 to 1.0).
        status_label: Optional domain-specific status label.
        metadata: Arbitrary additional model metadata (e.g., hyperparameters).

    Example:
        >>> pred = PredictionArtifact(
        ...     target_variable="Cooler Condition",
        ...     predicted_value="Efficiency Reduced",
        ...     confidence_or_probability=0.82,
        ...     status_label="Efficiency Reduced (20% tier)"
        ... )
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    target_variable: str = Field(
        ...,
        description="Name or identifier of the target variable being predicted.",
        min_length=1,
    )
    predicted_value: Any = Field(
        ...,
        description="The predicted class label, numerical value, or state.",
    )
    model_name: str | None = Field(
        default=None,
        description="Optional name or version identifier of the predictive model.",
    )
    confidence_or_probability: float | None = Field(
        default=None,
        description="Confidence score or probability of prediction (0.0 to 1.0).",
        ge=0.0,
        le=1.0,
    )
    status_label: str | None = Field(
        default=None,
        description="Domain status label (e.g., 'Efficiency Reduced').",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary additional model execution metadata.",
    )

    @classmethod
    def from_input(
        cls, data: PredictionArtifact | dict[str, Any]
    ) -> PredictionArtifact:
        """Create or validate PredictionArtifact from dict or instance.

        Args:
            data: PredictionArtifact instance or dictionary with prediction data.

        Returns:
            A validated PredictionArtifact instance.
        """
        if isinstance(data, cls):
            return data
        return cls.model_validate(data)


class XAIArtifact(BaseModel):
    """Represents raw explainability intermediate artifacts (Level 2).

    Encapsulates feature attributions, importance weights, baselines,
    or counterfactual examples generated by XAI algorithms (e.g., SHAP, LIME).

    Attributes:
        method: Name of the interpretability method (e.g., 'shap').
        feature_attributions: Mapping of feature names to numerical attribution weights.
        baseline_values: Optional baseline reference values used for attribution.
        counterfactuals: Optional list of counterfactual instances or perturbations.
        raw_artifacts: Arbitrary additional XAI outputs or diagnostic metrics.

    Example:
        >>> xai = XAIArtifact(
        ...     method="shap",
        ...     feature_attributions={"PS1": 0.45, "EPS1": 0.35, "TS2": 0.20}
        ... )
        >>> xai.top_features(n=2)
        [('PS1', 0.45), ('EPS1', 0.35)]
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    method: str = Field(
        default="feature_importance",
        description="Name of the XAI algorithm or method producing the artifacts.",
    )
    feature_attributions: dict[str, float] = Field(
        default_factory=dict,
        description="Mapping of feature names to their attribution scores.",
    )
    baseline_values: dict[str, Any] | None = Field(
        default=None,
        description="Optional baseline reference values used in attribution.",
    )
    counterfactuals: list[dict[str, Any]] | None = Field(
        default=None,
        description="Optional list of counterfactual examples or scenario shifts.",
    )
    raw_artifacts: dict[str, Any] = Field(
        default_factory=dict,
        description="Raw or algorithm-specific intermediate artifacts.",
    )

    def top_features(
        self, n: int = 5, absolute: bool = True
    ) -> list[tuple[str, float]]:
        """Return the top N most important features sorted by attribution weight.

        Args:
            n: Number of top features to return.
            absolute: If True, sorts by absolute attribution magnitude |score|.

        Returns:
            List of (feature_name, score) tuples in descending order of importance.
        """
        if not self.feature_attributions:
            return []

        key_fn = (lambda item: abs(item[1])) if absolute else (lambda item: item[1])
        sorted_items = sorted(
            self.feature_attributions.items(), key=key_fn, reverse=True
        )
        return sorted_items[:n]

    @classmethod
    def from_input(cls, data: XAIArtifact | dict[str, Any] | None) -> XAIArtifact:
        """Create or validate an XAIArtifact from input data.

        Args:
            data: XAIArtifact instance, dictionary, or None (returns default empty).

        Returns:
            A validated XAIArtifact instance.
        """
        if data is None:
            return cls()
        if isinstance(data, cls):
            return data
        return cls.model_validate(data)


class DomainContext(BaseModel):
    """Represents operational context and technical metadata.

    Managed by ContextManagerAgent (CMA) without requiring dense vector RAG.
    Can be initialized statically at startup and enriched iteratively per incident.

    Attributes:
        sensor_dictionary: Mapping of variable acronyms to physical descriptions.
        operational_thresholds: Safe operating ranges or engineering limits.
        documentation_snippets: Technical manual excerpts or procedures.
        system_hierarchy: Optional hierarchical taxonomy of subsystems.

    Example:
        >>> context = DomainContext()
        >>> context.add_sensor("PS1", "Axial pressure of main cooling pump")
        >>> context.add_document("manual", "Thermal dissipation guidelines...")
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    sensor_dictionary: dict[str, str] = Field(
        default_factory=dict,
        description="Mapping of variable acronyms/codes to physical definitions.",
    )
    operational_thresholds: dict[str, Any] = Field(
        default_factory=dict,
        description="Engineering threshold boundaries or safe operating ranges.",
    )
    documentation_snippets: dict[str, str] = Field(
        default_factory=dict,
        description="Relevant excerpts from technical manuals or operating procedures.",
    )
    system_hierarchy: dict[str, Any] | None = Field(
        default=None,
        description="Optional tree or hierarchy describing subsystem relationships.",
    )

    def add_sensor(self, sensor_id: str, description: str) -> None:
        """Add or update a sensor definition in the dictionary.

        Args:
            sensor_id: Acronym or tag of the sensor/variable (e.g., 'PS1').
            description: Physical domain description of what the sensor measures.
        """
        self.sensor_dictionary[sensor_id] = description

    def add_document(self, document_id: str, content: str) -> None:
        """Add or update a documentation snippet.

        Args:
            document_id: Key or title for the document section (e.g., 'cooling_manual').
            content: Textual content or excerpt of the document.
        """
        self.documentation_snippets[document_id] = content

    def add_threshold(self, metric: str, threshold_value: Any) -> None:
        """Add or update an operational threshold.

        Args:
            metric: The name or sensor key corresponding to the threshold.
            threshold_value: Value or range representing the operational limit.
        """
        self.operational_thresholds[metric] = threshold_value

    def merge(self, other: DomainContext | dict[str, Any]) -> DomainContext:
        """Create a new DomainContext by merging current data with another context.

        Args:
            other: Another DomainContext instance or dictionary.

        Returns:
            A new DomainContext instance containing combined and updated entries.
        """
        other_obj = self.from_input(other)
        merged_sensors = {**self.sensor_dictionary, **other_obj.sensor_dictionary}
        merged_thresholds = {
            **self.operational_thresholds,
            **other_obj.operational_thresholds,
        }
        merged_docs = {
            **self.documentation_snippets,
            **other_obj.documentation_snippets,
        }
        merged_hierarchy = other_obj.system_hierarchy or self.system_hierarchy

        return DomainContext(
            sensor_dictionary=merged_sensors,
            operational_thresholds=merged_thresholds,
            documentation_snippets=merged_docs,
            system_hierarchy=merged_hierarchy,
        )

    @classmethod
    def from_input(cls, data: DomainContext | dict[str, Any] | None) -> DomainContext:
        """Create or validate a DomainContext from input data.

        Args:
            data: A DomainContext instance, dictionary, or None (returns empty context).

        Returns:
            A validated DomainContext instance.
        """
        if data is None:
            return cls()
        if isinstance(data, cls):
            return data
        return cls.model_validate(data)


class AgentStepTrace(BaseModel):
    """Audit record capturing the execution of an individual agent step.

    Provides granular transparency and observability for multi-agent reasoning,
    timing benchmarks, and industrial compliance.

    Attributes:
        agent_name: Name of the agent executing the step (e.g., 'CMA', 'AA', 'EA').
        execution_time_ms: Wall-clock execution latency in milliseconds.
        summary: Concise summary of actions performed or output generated.
        status: Execution status ('success', 'error', 'refinement', 'fallback').
        details: Optional structured telemetry or diagnostic data.
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    agent_name: str = Field(
        ...,
        description="Identifier of the executing agent.",
        min_length=1,
    )
    execution_time_ms: float = Field(
        ...,
        description="Duration of the agent step in milliseconds.",
        ge=0.0,
    )
    summary: str = Field(
        ...,
        description="Concise description of the step's outcome or contribution.",
    )
    status: str = Field(
        default="success",
        description="Execution status outcome (e.g., 'success', 'error', 'fallback').",
    )
    details: dict[str, Any] = Field(
        default_factory=dict,
        description="Optional diagnostic data, intermediate scores, or parameters.",
    )


class ExplanationResponse(BaseModel):
    """Final contextualized response delivered by Explanation Layer (Level 3).

    Encapsulates natural language explanation, technical fidelity validation,
    refinement history, and complete audit trail.

    Attributes:
        narrative: Synthesized natural language explanation and recommendations.
        validation_score: Quality score by ValidatorAgent (0.0 to 10.0 scale).
        validation_passed: Flag indicating whether validation score reached threshold.
        validation_critique: Optional feedback or critique from ValidatorAgent.
        attempts_used: Total number of synthesis/refinement loops executed (>= 1).
        fallback_used: Flag indicating if emergency graceful degradation was triggered.
        execution_trace: Step-by-step trace of all participating agents.

    Example:
        >>> res = ExplanationResponse(
        ...     narrative="The 82% risk is driven by axial vibration (PS1)...",
        ...     validation_score=9.5,
        ...     validation_passed=True,
        ...     attempts_used=1
        ... )
    """

    model_config = ConfigDict(extra="allow", populate_by_name=True)

    narrative: str = Field(
        ...,
        description="Natural language explanation and operational recommendations.",
    )
    validation_score: float = Field(
        ...,
        description="Fidelity score evaluated by ValidatorAgent (0.0 to 10.0 scale).",
        ge=0.0,
        le=10.0,
    )
    validation_passed: bool = Field(
        ...,
        description="Whether the response satisfied the technical fidelity threshold.",
    )
    validation_critique: str | None = Field(
        default=None,
        description="Critique or feedback emitted by the ValidatorAgent.",
    )
    attempts_used: int = Field(
        default=1,
        description="Number of synthesis and refinement attempts performed.",
        ge=1,
    )
    fallback_used: bool = Field(
        default=False,
        description="True if narrative was generated via graceful fallback on failure.",
    )
    execution_trace: list[AgentStepTrace] = Field(
        default_factory=list,
        description="Sequential trace records of all agents involved in this turn.",
    )

    @field_validator("validation_score")
    @classmethod
    def round_score(cls, v: float) -> float:
        """Round validation score to two decimal places for consistency."""
        return round(v, 2)
